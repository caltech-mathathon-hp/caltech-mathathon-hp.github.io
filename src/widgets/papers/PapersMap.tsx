/**
 * PapersMap: the literature around HP-folding hardness as a timeline with theme lanes.
 *
 * x = year on a compressed axis (crowded years get more room, long empty stretches shrink,
 * a gap of more than BREAK_GAP years is cut out); one lane per theme (a paper sits in the
 * lane of its first theme); mark size = relevance to our question. Hovering or focusing a
 * paper draws its relations as arcs and dims the rest; selecting it opens a card with the
 * details and the relations as links. Theme chips filter the papers.
 *
 * Narrow containers (< NARROW px) get a list instead of the timeline (CSS container query
 * and JS agree on the threshold). Keyboard: Tab to the map, arrows move, Enter opens,
 * Escape closes. The URL hash #paper-<key> (the target of <Cite>) selects that paper, and
 * a 'pp:select' window event ({detail: {key}}) does the same (PapersList.astro sends it).
 *
 * Data: src/data/papers/papers.json (generated by scripts/build_papers.py).
 * Styles: ./styles.css, class prefix pp-, colours from tokens.css only.
 */
