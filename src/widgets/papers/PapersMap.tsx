const SSR_WIDTH = 940;

// ---------------------------------------------------------------- static layout (width-independent)

const YEARS = [...new Set(PAPERS.map((p) => p.year))].sort((a, b) => a - b);

/** Rows of marks per lane: the most papers sharing a year in that lane, at most 3. */
const LANE_ROWS = new Map(
  THEMES.map((t) => {
    const counts = new Map<number, number>();
    for (const p of PAPERS) if (laneOf(p) === t.id) counts.set(p.year, (counts.get(p.year) ?? 0) + 1);
    return [t.id, Math.min(3, Math.max(1, ...counts.values()))];
  }),
);
/** Columns a year needs (in its most crowded lane). */
const YEAR_COLS = new Map(
  YEARS.map((y) => [
    y,
    Math.max(
      1,
      ...THEMES.map((t) =>
        Math.ceil(PAPERS.filter((p) => laneOf(p) === t.id && p.year === y).length / LANE_ROWS.get(t.id)!),
      ),
    ),
  ]),
);

// Compressed axis in abstract units: each occupied year gets one unit per column; an empty
// year costs EMPTY_YEAR (FAR_YEAR beyond the fourth); gaps longer than BREAK_GAP are cut.
const EMPTY_YEAR = 0.4;
const FAR_YEAR = 0.1;
const BREAK_GAP = 15;
const BREAK_W = 1.6;
const END_PAD = 0.5;
interface Slot {
  year: number;
  start: number;
  width: number;
}
const SLOTS: Slot[] = [];
const BREAKS_U: number[] = [];
{
  let u = END_PAD;
  YEARS.forEach((y, i) => {
    if (i > 0) {
      const g = y - YEARS[i - 1];
      if (g > BREAK_GAP) {
        BREAKS_U.push(u + BREAK_W / 2);
        u += BREAK_W;
      } else {
        const e = g - 1;
        u += e <= 4 ? e * EMPTY_YEAR : 4 * EMPTY_YEAR + (e - 4) * FAR_YEAR;
      }
    }
    const w = YEAR_COLS.get(y)!;
    SLOTS.push({ year: y, start: u, width: w });
    u += w;
  });
  SLOTS.push({ year: Infinity, start: u + END_PAD, width: 0 }); // sentinel: total width
}
const TOTAL_U = SLOTS[SLOTS.length - 1].start;
const SLOT_OF = new Map(SLOTS.map((s) => [s.year, s]));

/** Position of a calendar year on the abstract axis, or null inside a cut gap / out of range. */
function yearToU(y: number): number | null {
  const i = SLOTS.findIndex((s) => s.year >= y);
  if (i < 0 || SLOTS[i].year === Infinity) return null;
  const s = SLOTS[i];
  if (s.year === y) return s.start + s.width / 2;
  if (i === 0) return null;
  const a = SLOTS[i - 1];
  if (s.year - a.year > BREAK_GAP) return null;
  const empty = s.year - a.year - 1;
  const endA = a.start + a.width;
  return endA + ((y - a.year - 0.5) * (s.start - endA)) / empty;
}

function radius(p: Paper): number {
  if (laneOf(p) === 'core') return 9;
  return [0, 4, 5.5, 7][p.relevance];
}

// ---------------------------------------------------------------- text measurement

const widthCache = new Map<string, number>();
let measureCtx: CanvasRenderingContext2D | null | undefined;
function textWidth(s: string, px: number, weight: number): number {
  const id = `${weight}|${px}|${s}`;
  const hit = widthCache.get(id);
  if (hit !== undefined) return hit;
  let w = s.length * px * 0.56;
  if (typeof document !== 'undefined') {
    if (measureCtx === undefined) measureCtx = document.createElement('canvas').getContext('2d');
    if (measureCtx) {
      const fam = getComputedStyle(document.documentElement).getPropertyValue('--font-sans').trim() || 'sans-serif';
      measureCtx.font = `${weight} ${px}px ${fam}`;
      w = measureCtx.measureText(s).width;
      widthCache.set(id, w);
    }
  }
  return w;
}

// ---------------------------------------------------------------- chart layout (width-dependent)

interface Pos {
  x: number;
  y: number;
  r: number;
}
interface LaneBox {
  theme: Theme;
  y0: number;
  y1: number;
  count: number;
}
interface Layout {
  W: number;
  H: number;
  gx: number;
  x1: number;
  axisY: number;
  lanes: LaneBox[];
  pos: Map<string, Pos>;
  ticks: { year: number; x: number }[];
  breaks: number[];
  order: Map<string, string[]>; // lane id → visible keys, left to right
}

function computeLayout(W: number, visible: (p: Paper) => boolean): Layout {
  const gx = W >= 860 ? 150 : 124;
  const x1 = W - 16;
  const unit = (x1 - gx) / TOTAL_U;
  const X = (u: number) => gx + u * unit;
  const pos = new Map<string, Pos>();
  const lanes: LaneBox[] = [];
  const order = new Map<string, string[]>();
  let y = 6;
  for (const t of THEMES) {
    const inLane = PAPERS.filter((p) => laneOf(p) === t.id && visible(p));
    if (!inLane.length) continue;
    const rows = LANE_ROWS.get(t.id)!;
    const rowH = t.id === 'core' ? 30 : 20;
    const h = Math.max(48, rows * rowH + 18);
    const top = y + (h - rows * rowH) / 2;
    const placed: Pos[] = [];
    for (const yr of YEARS) {
      const g = inLane
        .filter((p) => p.year === yr)
        .sort((a, b) => b.relevance - a.relevance || a.key.localeCompare(b.key));
      if (!g.length) continue;
      const used = Math.min(g.length, rows);
      const cols = Math.ceil(g.length / used);
      const slot = SLOT_OF.get(yr)!;
      const x0 = X(slot.start + slot.width / 2) - ((cols - 1) * unit) / 2;
      const free = rows - used;
      const offsets = free > 0 ? [...new Set([free / 2, 0, free])] : [0];
      let best: Pos[] = [];
      let bestScore = -Infinity;
      for (const off of offsets) {
        const pts = g.map((p, i) => ({
          x: x0 + Math.floor(i / used) * unit,
          y: top + (off + (i % used) + 0.5) * rowH,
          r: radius(p),
        }));
        let score = Infinity;
        for (const a of pts)
          for (const b of placed) score = Math.min(score, Math.hypot(a.x - b.x, a.y - b.y) - (a.r + b.r + 3));
        if (score >= 0) {
          best = pts;
          break;
        }
        if (score > bestScore) {
          bestScore = score;
          best = pts;
        }
      }
      g.forEach((p, i) => pos.set(p.key, best[i]));
      placed.push(...best);
    }
    order.set(
      t.id,
      inLane.map((p) => p.key).sort((a, b) => pos.get(a)!.x - pos.get(b)!.x || pos.get(a)!.y - pos.get(b)!.y),
    );
    lanes.push({ theme: t, y0: y, y1: y + h, count: inLane.length });
    y += h;
  }
  const axisY = y + 4;

  const cands: number[] = [];
  if (YEARS.length > 1 && YEARS[1] - YEARS[0] > BREAK_GAP) cands.push(YEARS[0]);
  for (let yr = Math.ceil(YEARS[0] / 5) * 5; yr <= YEARS[YEARS.length - 1]; yr += 5) cands.push(yr);
  const ticks: { year: number; x: number }[] = [];
  for (const yr of cands) {
    const u = yearToU(yr);
    if (u === null) continue;
    const x = X(u);
    if (ticks.length && x - ticks[ticks.length - 1].x < 36) continue;
    ticks.push({ year: yr, x });
  }
  return { W, H: axisY + 26, gx, x1, axisY, lanes, pos, ticks, breaks: BREAKS_U.map(X), order };
}

// ---------------------------------------------------------------- labels

interface Box {
  x0: number;
  y0: number;
  x1: number;
  y1: number;
}
interface PlacedLabel {
  key: string;
  x: number;
  y: number;
  name: string;
  badge?: string;
  strong: boolean;
}
const NAME_PX = 12;
const BADGE_PX = 11;

function placeLabels(L: Layout, keys: string[], must: string | null): PlacedLabel[] {
  const out: PlacedLabel[] = [];
  const boxes: Box[] = [];
  const marks = [...L.pos.entries()];
  const hits = (b: Box, own: string) =>
    b.x0 < L.gx - 4 ||
    b.x1 > L.W - 2 ||
    b.y0 < 1 ||
    b.y1 > L.axisY - 1 ||
    boxes.some((o) => b.x0 < o.x1 + 3 && b.x1 > o.x0 - 3 && b.y0 < o.y1 + 1 && b.y1 > o.y0 - 1) ||
    marks.some(
      ([k, m]) => k !== own && b.x0 < m.x + m.r + 1 && b.x1 > m.x - m.r - 1 && b.y0 < m.y + m.r && b.y1 > m.y - m.r,
    );
  for (const key of keys) {
    const p = BY_KEY.get(key);
    const m = L.pos.get(key);
    if (!p || !m) continue;
    const strong = laneOf(p) === 'core' || key === must;
    const name = shortAuthors(p);
    const badge = laneOf(p) === 'core' ? p.badge : undefined;
    const w = Math.max(textWidth(name, NAME_PX, strong ? 650 : 520), badge ? textWidth(badge, BADGE_PX, 450) : 0);
    const h = badge ? 28 : 14;
    const gap = m.r + 4;
    const cands: Box[] = [
      { x0: m.x + gap, x1: m.x + gap + w, y0: m.y - h / 2, y1: m.y + h / 2 },
      { x0: m.x - gap - w, x1: m.x - gap, y0: m.y - h / 2, y1: m.y + h / 2 },
      { x0: m.x - w / 2, x1: m.x + w / 2, y0: m.y - m.r - 3 - h, y1: m.y - m.r - 3 },
      { x0: m.x - w / 2, x1: m.x + w / 2, y0: m.y + m.r + 3, y1: m.y + m.r + 3 + h },
    ];
    let box = cands.find((b) => !hits(b, key));
    if (!box && key === must) box = cands.find((b) => b.x0 >= L.gx - 4 && b.x1 <= L.W - 2) ?? cands[0];
    if (!box) continue;
    boxes.push(box);
    out.push({ key, x: box.x0, y: box.y0, name, badge, strong });
  }
  return out;
}

function arcPath(a: Pos, b: Pos, H: number): string {
  const dx = b.x - a.x;
  const dy = b.y - a.y;
  const d = Math.hypot(dx, dy) || 1;
  let nx = -dy / d;
  let ny = dx / d;
  const down = (a.y + b.y) / 2 < H * 0.3; // near the top: bow downwards to stay inside
  if ((ny > 0) !== down || (Math.abs(ny) < 1e-6 && nx > 0)) {
    nx = -nx;
    ny = -ny;
  }
  const bulge = Math.min(90, Math.max(14, d * 0.24));
  const cx = (a.x + b.x) / 2 + nx * bulge;
  const cy = (a.y + b.y) / 2 + ny * bulge;
  return `M${a.x.toFixed(1)},${a.y.toFixed(1)} Q${cx.toFixed(1)},${cy.toFixed(1)} ${b.x.toFixed(1)},${b.y.toFixed(1)}`;
}

function linkLabel(url: string): string {
  if (/github\.com|isa-afp\.org/.test(url)) return 'Open the repository';
  if (/ocw\.mit\.edu/.test(url)) return 'Open the lectures';
  if (/gfalop\.org/.test(url)) return 'Open the book page';
  return 'Open the paper';
}

const prefersReducedMotion = () =>
  typeof matchMedia !== 'undefined' && matchMedia('(prefers-reduced-motion: reduce)').matches;

// ---------------------------------------------------------------- component

type FocusTarget = { key: string; where: 'mark' | 'row' | 'card' | 'auto' } | null;

export default function PapersMap() {
  const rootRef = useRef<HTMLDivElement>(null);
  const [width, setWidth] = useState(SSR_WIDTH);
  const [fontsReady, setFontsReady] = useState(0);
  const [filter, setFilter] = useState<Set<string>>(() => new Set());
  // List view: groups the reader opened or closed by hand (otherwise: open if core or filtered).
  const [groupOpen, setGroupOpen] = useState<Map<string, boolean>>(() => new Map());
  const [selected, setSelected] = useState<string | null>(null);
  const [hovered, setHovered] = useState<string | null>(null);
  const [focused, setFocused] = useState<string | null>(null);
  const [active, setActive] = useState<string>(PAPERS.find((p) => laneOf(p) === 'core')?.key ?? PAPERS[0].key);
  const markRefs = useRef(new Map<string, SVGGElement>());
  const rowRefs = useRef(new Map<string, HTMLButtonElement>());
  const cardTitleRef = useRef<HTMLParagraphElement>(null);
  const pendingFocus = useRef<FocusTarget>(null);

  const mode: 'chart' | 'list' = width < NARROW ? 'list' : 'chart';
  const visible = (p: Paper) => filter.size === 0 || p.themes.some((t) => filter.has(t));

  // Size: follow the container.
  useLayoutEffect(() => {
    const el = rootRef.current;
    if (!el) return;
    setWidth(el.clientWidth);
    const ro = new ResizeObserver((entries) => {
      const w = Math.round(entries[0].contentRect.width);
      if (w > 0) setWidth(w);
    });
    ro.observe(el);
    document.fonts?.ready.then(() => {
      widthCache.clear();
      setFontsReady((n) => n + 1);
    });
    return () => ro.disconnect();
  }, []);

  /** Select a paper, making sure the filter shows it. */
  const reveal = (key: string, focus: NonNullable<FocusTarget>['where'] | null) => {
    const p = BY_KEY.get(key);
    if (!p) return;
    setFilter((f) => (f.size === 0 || p.themes.some((t) => f.has(t)) ? f : new Set([...f, p.themes[0]])));
    setGroupOpen((g) => (g.get(laneOf(p)) ? g : new Map(g).set(laneOf(p), true)));
    setSelected(key);
    setActive(key);
    if (focus) pendingFocus.current = { key, where: focus };
  };

  // Hash (#paper-<key>, the target of <Cite>) and the 'pp:select' event from the static list.
  useEffect(() => {
    const fromHash = () => {
      const m = /^#paper-(.+)$/.exec(decodeURIComponent(location.hash));
      if (m && BY_KEY.has(m[1])) reveal(m[1], null);
    };
    const onSelect = (e: Event) => {
      const key = (e as CustomEvent<{ key?: string }>).detail?.key;
      if (key && BY_KEY.has(key)) reveal(key, 'auto');
    };
    fromHash();
    window.addEventListener('hashchange', fromHash);
    window.addEventListener('pp:select', onSelect);
    return () => {
      window.removeEventListener('hashchange', fromHash);
      window.removeEventListener('pp:select', onSelect);
    };
  }, []);

  // Move focus where an action asked for it, once the new state is rendered.
  useEffect(() => {
    const f = pendingFocus.current;
    if (!f) return;
    pendingFocus.current = null;
    const where = f.where === 'auto' ? (mode === 'chart' ? 'mark' : 'row') : f.where;
    const el =
      where === 'mark'
        ? markRefs.current.get(f.key)
        : where === 'row'
          ? rowRefs.current.get(f.key)
          : cardTitleRef.current;
    el?.focus({ preventScroll: where === 'mark' });
    if (where === 'row' && el) el.scrollIntoView({ block: 'nearest', behavior: prefersReducedMotion() ? 'auto' : 'smooth' });
  });

  const L = useMemo(() => computeLayout(Math.max(width, NARROW), visible), [width, filter, fontsReady]);

  // Keep the roving tab stop on a visible paper.
  useEffect(() => {
    if (!L.pos.has(active)) {
      const first = L.lanes[0] && L.order.get(L.lanes[0].theme.id)?.[0];
      if (first) setActive(first);
    }
  }, [L]);
  useEffect(() => {
    if (selected && !L.pos.has(selected)) setSelected(null);
  }, [L]);

  const hl = hovered ?? focused ?? selected; // the paper whose relations are drawn
  const hlLinks = hl ? (LINKS.get(hl) ?? []).filter((l) => L.pos.has(l.other)) : [];
  const related = new Set(hlLinks.map((l) => l.other));

  const labelKeys = useMemo(() => {
    const base = PAPERS.filter((p) => L.pos.has(p.key) && (laneOf(p) === 'core' || p.relevance === 3));
    if (!hl) return base.sort((a, b) => radius(b) - radius(a)).map((p) => p.key);
    const rel = [...related].map((k) => BY_KEY.get(k)!).sort((a, b) => radius(b) - radius(a));
    const rest = base.filter((p) => p.key !== hl && !related.has(p.key) && laneOf(p) === 'core');
    return [hl, ...rel.map((p) => p.key), ...rest.map((p) => p.key)];
  }, [L, hl]);
  const labels = useMemo(() => placeLabels(L, labelKeys, hl), [L, labelKeys, hl]);

  // ---------------- interaction

  const toggleTheme = (id: string) =>
    setFilter((f) => {
      const n = new Set(f);
      if (n.has(id)) n.delete(id);
      else n.add(id);
      return n;
    });

  const choose = (key: string, where: NonNullable<FocusTarget>['where'] | null = null) => {
    setSelected((s) => (s === key ? null : key));
    setActive(key);
    if (where) pendingFocus.current = { key, where };
  };

  const onChartKey = (e: KeyboardEvent) => {
    const cur = active;
    const p = BY_KEY.get(cur);
    if (!p || !L.pos.has(cur)) return;
    const laneIds = L.lanes.map((l) => l.theme.id);
    const li = laneIds.indexOf(laneOf(p));
    const row = L.order.get(laneOf(p)) ?? [];
    const i = row.indexOf(cur);
    let next: string | undefined;
    switch (e.key) {
      case 'ArrowRight':
        next = row[Math.min(row.length - 1, i + 1)];
        break;
      case 'ArrowLeft':
        next = row[Math.max(0, i - 1)];
        break;
      case 'Home':
        next = row[0];
        break;
      case 'End':
        next = row[row.length - 1];
        break;
      case 'ArrowDown':
      case 'ArrowUp': {
        const lj = li + (e.key === 'ArrowDown' ? 1 : -1);
        if (lj < 0 || lj >= laneIds.length) break;
        const x = L.pos.get(cur)!.x;
        const other = L.order.get(laneIds[lj]) ?? [];
        next = other.reduce((b, k) => (Math.abs(L.pos.get(k)!.x - x) < Math.abs(L.pos.get(b)!.x - x) ? k : b), other[0]);
        break;
      }
      case 'Enter':
      case ' ':
        e.preventDefault();
        choose(cur);
        return;
      case 'Escape':
        if (selected) {
          e.preventDefault();
          setSelected(null);
        }
        return;
      default:
        return;
    }
    e.preventDefault();
    if (next && next !== cur) {
      setActive(next);
      pendingFocus.current = { key: next, where: 'mark' };
    }
  };

  // ---------------- render pieces

  const chips = (
    <div class="pp-toolbar" role="group" aria-label="Filter papers by theme">
      <span class="pp-toolbar-label">Themes</span>
      {THEMES.map((t) => {
        const n = PAPERS.filter((p) => p.themes.includes(t.id)).length;
        return (
          <button
            type="button"
            class="pp-chip"
            aria-pressed={filter.has(t.id)}
            style={{ '--c': `var(${t.color ?? '--fg-muted'})` } as CSSProperties}
            onClick={() => toggleTheme(t.id)}
            title={t.description}
          >
            <span class="pp-dot" aria-hidden="true" />
            {t.short ?? t.label}
            <span class="pp-chip-n">{n}</span>
          </button>
        );
      })}
      {filter.size > 0 && (
        <button type="button" class="pp-chip pp-chip-reset" onClick={() => setFilter(new Set())}>
          Show all
        </button>
      )}
    </div>
  );

  const card = (key: string, compact: boolean) => (
    <Card
      p={BY_KEY.get(key)!}
      compact={compact}
      titleRef={cardTitleRef}
      onClose={() => {
        setSelected(null);
        pendingFocus.current = { key, where: mode === 'chart' ? 'mark' : 'row' };
      }}
      onSelect={(k) => reveal(k, 'card')}
    />
  );

  const hint = (
    <div class="pp-hint">
      <p>
        Click a paper, or press Enter on it, to see its details here. Start with the two hardness proofs:
      </p>
      <p class="pp-hint-actions">
        {PAPERS.filter((p) => laneOf(p) === 'core').map((p) => (
          <button type="button" class="btn" onClick={() => reveal(p.key, 'card')}>
            <span class="pp-dot" style={{ '--c': colorOf('core') } as CSSProperties} aria-hidden="true" />
            {shortAuthors(p)} ({p.year}){p.badge ? `, ${p.badge}` : ''}
          </button>
        ))}
      </p>
    </div>
  );

  const shown = hl ? BY_KEY.get(hl) : undefined; // the paper named in the read-out line
  const shownLinks = shown ? (LINKS.get(shown.key)?.length ?? 0) : 0;

  return (
    <div class="pp" ref={rootRef} data-mode={mode}>
      {chips}

      {/* ---------------- timeline (wide containers) */}
      <div class="pp-chart">
        <div class="pp-svgwrap" onMouseLeave={() => setHovered(null)}>
          <div class="pp-frame">
          <svg
            class={`pp-svg${hl ? ' pp-has-hl' : ''}`}
            viewBox={`0 0 ${L.W} ${L.H}`}
            width={L.W}
            height={L.H}
            role="group"
            aria-label={`Timeline of ${L.pos.size} papers in ${L.lanes.length} themes`}
            aria-describedby="pp-keys"
            onKeyDown={onChartKey}
          >
            <g aria-hidden="true">
              {L.lanes.map((ln, i) => (
                <g key={ln.theme.id} class={`pp-lane${ln.theme.id === 'core' ? ' pp-lane-core' : ''}`}>
                  <rect x={0} y={ln.y0} width={L.W} height={ln.y1 - ln.y0} class="pp-lane-bg" />
                  {i > 0 && <line x1={0} x2={L.W} y1={ln.y0} y2={ln.y0} class="pp-lane-rule" />}
                  <circle
                    cx={14}
                    cy={(ln.y0 + ln.y1) / 2 - 7}
                    r={4}
                    style={{ fill: colorOf(ln.theme.id) }}
                  />
                  <text x={24} y={(ln.y0 + ln.y1) / 2 - 3} class="pp-lane-name">
                    {ln.theme.short ?? ln.theme.label}
                  </text>
                  <text x={24} y={(ln.y0 + ln.y1) / 2 + 12} class="pp-lane-count">
                    {ln.count} {ln.count === 1 ? 'paper' : 'papers'}
                  </text>
                </g>
              ))}
              {L.ticks.map((t) => (
                <line x1={t.x} x2={t.x} y1={L.lanes[0]?.y0 ?? 0} y2={L.axisY} class="pp-grid" />
              ))}
              <line x1={L.gx - 6} x2={L.x1 + 6} y1={L.axisY} y2={L.axisY} class="pp-axis" />
              {L.ticks.map((t) => (
                <text x={t.x} y={L.axisY + 16} class="pp-tick">
                  {t.year}
                </text>
              ))}
              {L.breaks.map((x) => (
                <g class="pp-break" transform={`translate(${x},${L.axisY})`}>
                  <rect x={-5} y={-6} width={10} height={12} class="pp-break-bg" />
                  <path d="M-5,5 L-1,-5 M1,5 L5,-5" />
                </g>
              ))}
            </g>

            <g class="pp-arcs" aria-hidden="true">
              {hl &&
                L.pos.has(hl) &&
                hlLinks.map((l) => (
                  <path
                    d={arcPath(L.pos.get(hl)!, L.pos.get(l.other)!, L.H)}
                    class={`pp-arc${REL[l.kind].soft ? ' pp-arc-soft' : ''}${REL[l.kind].alarm ? ' pp-arc-alarm' : ''}`}
                  />
                ))}
            </g>

            <g class="pp-marks">
              {PAPERS.filter((p) => L.pos.has(p.key)).map((p) => {
                const m = L.pos.get(p.key)!;
                const dim = hl !== null && p.key !== hl && !related.has(p.key);
                const nLinks = LINKS.get(p.key)?.length ?? 0;
                return (
                  <g
                    key={p.key}
                    ref={(el) => {
                      if (el) markRefs.current.set(p.key, el as SVGGElement);
                      else markRefs.current.delete(p.key);
                    }}
                    class={`pp-mark rel-${p.relevance}${laneOf(p) === 'core' ? ' pp-core' : ''}${dim ? ' pp-dim' : ''}${
                      selected === p.key ? ' pp-selected' : ''
                    }${hl === p.key ? ' pp-hl' : ''}`}
                    transform={`translate(${m.x.toFixed(1)},${m.y.toFixed(1)})`}
                    style={{ '--c': colorOf(laneOf(p)) } as CSSProperties}
                    role="button"
                    tabIndex={active === p.key ? 0 : -1}
                    aria-pressed={selected === p.key}
                    aria-label={`${shortAuthors(p)}, ${p.year}: ${p.title}. ${THEME.get(laneOf(p))?.label}. ${
                      nLinks
                    } ${nLinks === 1 ? 'connection' : 'connections'}.`}
                    onMouseEnter={() => setHovered(p.key)}
                    onMouseLeave={() => setHovered((h) => (h === p.key ? null : h))}
                    onFocus={() => {
                      setFocused(p.key);
                      setActive(p.key);
                    }}
                    onBlur={() => setFocused((f) => (f === p.key ? null : f))}
                    onClick={() => choose(p.key)}
                  >
                    <circle r={Math.max(m.r + 5, 11)} class="pp-hit" />
                    {laneOf(p) === 'core' && <circle r={m.r + 4} class="pp-halo" />}
                    <circle r={m.r} class="pp-dotmark" />
                    <circle r={m.r + 3.5} class="pp-ring" />
                  </g>
                );
              })}
            </g>

            <g class="pp-labels" aria-hidden="true">
              {labels.map((lb) => {
                const p = BY_KEY.get(lb.key)!;
                const dim = hl !== null && lb.key !== hl && !related.has(lb.key);
                return (
                  <text
                    class={`pp-label${lb.strong ? ' pp-label-strong' : ''}${dim ? ' pp-dim' : ''}`}
                    x={lb.x}
                    y={lb.y + NAME_PX - 1}
                    onMouseEnter={() => setHovered(p.key)}
                    onClick={() => choose(p.key)}
                  >
                    {lb.name}
                    {lb.badge && (
                      <tspan x={lb.x} dy={BADGE_PX + 3} class="pp-label-badge">
                        {lb.badge}
                      </tspan>
                    )}
                  </text>
                );
              })}
            </g>
          </svg>
          <p class="pp-readout" aria-hidden="true">
            {shown ? (
              <>
                <span class="pp-dot" style={{ '--c': colorOf(laneOf(shown)) } as CSSProperties} />
                <span class="pp-readout-name">
                  {shortAuthors(shown)} ({shown.year})
                </span>
                <span class="pp-readout-title">{shown.title}</span>
                <span class="pp-readout-n">
                  {shownLinks} {shownLinks === 1 ? 'connection' : 'connections'}
                </span>
              </>
            ) : (
              <span class="pp-readout-idle">Hover over a paper, or tab to it, to see its title and connections.</span>
            )}
          </p>
          </div>
        </div>

        <Legend />
        <p id="pp-keys" class="visually-hidden">
          Use the arrow keys to move between papers: left and right within a theme, up and down between themes. Press
          Enter to open a paper's details and Escape to close them.
        </p>

        <div class="pp-panel" aria-live="polite">
          {mode === 'chart' && (selected && BY_KEY.has(selected) ? card(selected, false) : hint)}
        </div>
      </div>

      {/* ---------------- list (narrow containers) */}
      <div class="pp-listview">
        {THEMES.map((t) => {
          const ps = PAPERS.filter((p) => laneOf(p) === t.id && visible(p));
          if (!ps.length) return null;
          const expanded = groupOpen.get(t.id) ?? (t.id === 'core' || filter.size > 0);
          return (
            <div class="pp-lgroup" key={t.id}>
              <button
                type="button"
                class="pp-lhead"
                aria-expanded={expanded}
                aria-controls={`pp-lgroup-${t.id}`}
                style={{ '--c': colorOf(t.id) } as CSSProperties}
                onClick={() => {
                  setGroupOpen((g) => new Map(g).set(t.id, !expanded));
                  if (expanded && selected && ps.some((p) => p.key === selected)) setSelected(null);
                }}
              >
                <span class="pp-lchev" aria-hidden="true" />
                <span class="pp-dot" aria-hidden="true" />
                {t.label}
                <span class="pp-chip-n">{ps.length}</span>
              </button>
              <ul class="pp-rows" id={`pp-lgroup-${t.id}`} hidden={!expanded}>
                {ps.map((p) => {
                  const open = selected === p.key;
                  return (
                    <li key={p.key}>
                      <button
                        type="button"
                        class={`pp-row${open ? ' pp-row-open' : ''}`}
                        aria-expanded={open}
                        aria-controls={open ? `pp-lcard-${p.key}` : undefined}
                        ref={(el) => {
                          if (el) rowRefs.current.set(p.key, el);
                          else rowRefs.current.delete(p.key);
                        }}
                        onClick={() => choose(p.key)}
                        style={{ '--c': colorOf(t.id), '--s': `${radius(p) * 1.6}px` } as CSSProperties}
                      >
                        <span class="pp-row-year">{p.year}</span>
                        <span class="pp-row-mark" aria-hidden="true">
                          <span />
                        </span>
                        <span class="pp-row-main">
                          <span class="pp-row-name">
                            {shortAuthors(p)}
                            {p.badge && <span class="pp-row-badge"> · {p.badge}</span>}
                          </span>
                          <span class="pp-row-title">{p.title}</span>
                        </span>
                      </button>
                      {open && mode === 'list' && (
                        <div id={`pp-lcard-${p.key}`} class="pp-lcard">
                          {card(p.key, true)}
                        </div>
                      )}
                    </li>
                  );
                })}
              </ul>
            </div>
          );
        })}
      </div>
    </div>
  );
}

// ---------------------------------------------------------------- card

function Card(props: {
  p: Paper;
  compact: boolean;
  titleRef: { current: HTMLParagraphElement | null };
  onClose: () => void;
  onSelect: (key: string) => void;
}) {
  const { p, compact, titleRef, onClose, onSelect } = props;
  const links: Link[] = LINKS.get(p.key) ?? [];
  const rel = RELEVANCE[p.relevance];
  return (
    <article class={`pp-card${compact ? ' pp-card-compact' : ''}`} aria-labelledby={`pp-title-${p.key}`}>
      <div class="pp-card-top">
        <p class="pp-card-meta">
          {p.themes.map((t) => (
            <span class="pp-tag" style={{ '--c': colorOf(t) } as CSSProperties}>
              <span class="pp-dot" aria-hidden="true" />
              {THEME.get(t)?.label}
            </span>
          ))}
          {rel.mark && (
            <span class="pp-tag">
              <span class="pp-ref-mark" aria-hidden="true">
                {rel.mark}
              </span>
              {rel.label}
            </span>
          )}
        </p>
        <button type="button" class="btn ghost pp-close" aria-label="Close details" onClick={onClose}>
          <svg viewBox="0 0 16 16" width="14" height="14" aria-hidden="true">
            <path d="M3 3 L13 13 M13 3 L3 13" />
          </svg>
        </button>
      </div>
      <p class="pp-card-title" id={`pp-title-${p.key}`} tabIndex={-1} ref={titleRef}>
        {p.title}
      </p>
      <p class="pp-card-by">
        {joinAuthors(p.authors)} · {p.year}
        {p.venue && <span class="pp-card-venue"> · {p.venue}</span>}
      </p>
      <div class="pp-card-cols">
        <div class="pp-card-main">
          <p class="pp-card-take">
            {p.gist}
            {p.takeaway && ` ${p.takeaway}`}
          </p>
          {p.why && (
            <p class="pp-card-why">
              <span class="pp-card-sub">Why it matters</span> {p.why}
            </p>
          )}
          <p class="pp-card-status">{statusLine(p)}</p>
          <p class="pp-card-links">
            {p.url && (
              <a href={p.url} target="_blank" rel="noopener noreferrer">
                {linkLabel(p.url)} <span aria-hidden="true">↗</span>
              </a>
            )}
            <a href={`#paper-${p.key}`}>
              Show in the list <span aria-hidden="true">↓</span>
            </a>
          </p>
        </div>
        <div class="pp-card-rel">
          <p class="pp-card-sub">
            Connections <span class="pp-chip-n">{links.length}</span>
          </p>
          {links.length ? (
            <ul class="pp-rel-list">
              {links.map((l) => {
                const o = BY_KEY.get(l.other)!;
                return (
                  <li class={`pp-rel${REL[l.kind].alarm ? ' pp-rel-alarm' : ''}`}>
                    <span class="pp-rel-kind">{cap(relLabel(l))}</span>{' '}
                    <button
                      type="button"
                      class="pp-rel-link"
                      style={{ '--c': colorOf(laneOf(o)) } as CSSProperties}
                      onClick={() => onSelect(o.key)}
                    >
                      <span class="pp-dot" aria-hidden="true" />
                      {shortAuthors(o)} ({o.year})
                    </button>
                    {l.note && <span class="pp-rel-note">{l.note}</span>}
                  </li>
                );
              })}
            </ul>
          ) : (
            <p class="pp-muted">No connections recorded in our notes.</p>
          )}
        </div>
      </div>
    </article>
  );
}

